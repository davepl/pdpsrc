#!/usr/bin/env python3
"""Pre-expand tmux tree implementations for the memory-limited native cpp.

Run on the host after changing upstream/compat/tree.h or a *_GENERATE call:
    python3 tools/generate_native_trees.py
The original macro algorithms remain authoritative and are kept for host builds.
Generated files retain tree.h's license and differ only in preprocessing/spacing.
"""
from pathlib import Path
import argparse
import re
import subprocess

CALL = re.compile(r'^(?:RB|SPLAY)_GENERATE(?:_STATIC)?\s*\([^;]+\);', re.M)
TOKENS = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|[A-Za-z_]\w*|[0-9]+|[^\s]')


def format_c(raw):
    """Break at existing whitespace and ;{} outside literals; retain tokens."""
    output = []
    line = []
    quote = None
    escape = False
    pending_space = False

    def flush():
        if line:
            output.append(''.join(line).strip())
            line.clear()

    for ch in raw:
        if quote:
            line.append(ch)
            if escape:
                escape = False
            elif ch == '\\':
                escape = True
            elif ch == quote:
                quote = None
            continue
        if ch.isspace():
            pending_space = True
            continue
        if pending_space and line:
            if len(line) >= 110:
                flush()
            else:
                line.append(' ')
        pending_space = False
        line.append(ch)
        if ch in {'"', "'"}:
            quote = ch
        elif ch in ';{}':
            flush()
    flush()
    result = '\n'.join(output) + '\n'
    if TOKENS.findall(raw) != TOKENS.findall(result):
        raise ValueError('Formatting changed generated C tokens')
    if max(map(len, result.splitlines()), default=0) > 120:
        raise ValueError('Generated C has a physical line longer than 120 columns')
    return result


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    ap.add_argument('--cc', default='clang')
    args = ap.parse_args()
    root = args.root.resolve()
    tree = root / 'upstream/compat/tree.h'
    license_text = tree.read_text().split('#ifndef', 1)[0]
    output_dir = root / 'native/trees'
    output_dir.mkdir(parents=True, exist_ok=True)
    count = 0
    for source in sorted((root / 'upstream').rglob('*.c')):
        text = source.read_text()
        calls = list(CALL.finditer(text))
        if not calls:
            continue
        if len(calls) != 1:
            raise ValueError(f'{source}: expected one tree generation call')
        call = calls[0].group()
        unit = re.sub(r'\W', '_', source.stem)
        preprocessing = ('#define __attribute__(x)\n#define __inline\n'
                         '#include "' + str(tree) + '"\n' + call + '\n')
        expanded = subprocess.run([args.cc, '-E', '-P', '-x', 'c', '-'],
                                  input=preprocessing, text=True,
                                  capture_output=True, check=True).stdout
        if re.search(r'\b(?:RB|SPLAY)_[A-Z_]+\s*\(', expanded):
            raise ValueError(f'{source}: a tree macro was not fully expanded')
        generated = ('/* Generated by tools/generate_native_trees.py from:\n * ' + call +
                     '\n * Do not edit this file; edit the macro call or compat/tree.h.\n */\n' +
                     license_text + format_c(expanded))
        target = output_dir / (unit + '.inc')
        target.write_text(generated)
        include = '#include "../native/trees/' + unit + '.inc"'
        if include not in text:
            replacement = ('#if defined(TMUX_NATIVE_211BSD) || defined(PDP11_NATIVE)\n' +
                           include + '\n#else\n' + call + '\n#endif')
            text = text[:calls[0].start()] + replacement + text[calls[0].end():]
            source.write_text(text)
        count += 1
        print(f'{source.name}: {target.relative_to(root)}, {len(expanded)} expanded bytes')
    print(f'Generated {count} tree implementations')


if __name__ == '__main__':
    main()
