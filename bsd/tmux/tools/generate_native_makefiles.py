#!/usr/bin/env python3
"""Keep individual 2.11BSD make processes within their 16-bit data space.

The complete source manifest is native/objects-full.list. Generated files select
the milestone or full profile; clean shared objects before changing profile.
"""

import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CHUNK_SIZE = 8
CC = '../tools/cc211'
BASE_CFLAGS = ('-O -DTMUX_NATIVE_211BSD -DPDP11_NATIVE -I../native -I. '
               '-t01p -B../native/compiler/')
SHARED_COMMANDS = {'cmd-generic.o', 'cmd-list.o', 'cmd-string.o'}
MILESTONE_OMIT = {'options-cmd.o', 'layout-set.o', 'window-copy.o',
                  'window-choose.o', 'window-clock.o'}
GENERATED = '# Generated by tools/generate_native_makefiles.py.'


def read_full_objects(root):
    path = root / 'native/objects-full.list'
    objects = [line.strip() for line in path.read_text().splitlines()
               if line.strip() and not line.lstrip().startswith('#')]
    if not objects or len(objects) != len(set(objects)):
        raise ValueError('Full object manifest is empty or contains duplicates')
    for name in objects:
        if not re.fullmatch(r'(?:compat/|\.\./native/)?[\w-]+\.o', name):
            raise ValueError('Invalid object name in full manifest: ' + name)
        source = root / 'upstream' / (name[:-2] + '.c')
        if not source.is_file():
            raise ValueError('Missing canonical source: ' + str(source))
    return objects


def select_objects(root, objects, profile):
    if profile == 'full':
        return list(objects)
    text = (root / 'upstream/cmd.c').read_text()
    start = text.index('#ifdef TMUX_MILESTONE', text.index('cmd_table[]'))
    branch = text[start:].split('#else', 1)[0]
    commands = re.findall(r'&cmd_([a-z_]+)_entry', branch)
    if len(commands) != 26 or len(commands) != len(set(commands)):
        raise ValueError('Expected the explicit 26-command milestone allowlist')
    keep = {'cmd-' + name.replace('_', '-') + '.o' for name in commands}
    keep |= SHARED_COMMANDS
    missing = keep - set(objects)
    if missing:
        raise ValueError('Full manifest lacks milestone objects: ' + ', '.join(sorted(missing)))
    return [name for name in objects if name not in MILESTONE_OMIT
            and (not name.startswith('cmd-') or name in keep)]


def chunks(objects):
    return [('G%02d' % (index // CHUNK_SIZE + 1), objects[index:index + CHUNK_SIZE])
            for index in range(0, len(objects), CHUNK_SIZE)]


def child_makefile(root, name, objects, flags):
    text = GENERATED + ' Run from upstream.\n'
    text += 'CC=' + CC + '\nCFLAGS=' + flags + '\n'
    text += 'OBJS=' + ' '.join(objects) + '\n\nall: ${OBJS}\n\n'
    text += ('${OBJS}: tmux.h tmux-full.h tmux-native.h config.h compat.h '
             '../native/termios.h ../Makefile.211bsd ../native-mk/' + name + '.mk\n')
    for obj in objects:
        source = obj[:-2] + '.c'
        wrapped = source if source.startswith('../native/') else '../native-src/' + source
        unit = re.sub(r'\W', '_', Path(source).stem)
        text += '\n' + obj + ': ' + source
        if wrapped != source:
            text += ' ' + wrapped
        text += '\n\t${CC} ${CFLAGS} -DPDP11_UNIT_' + unit
        text += ' -c ' + wrapped + ' -o ' + obj + '\n'
        tree = root / 'native/trees' / (unit + '.inc')
        if tree.exists():
            text += obj + ': ../native/trees/' + tree.name + '\n'
        if obj == 'utf8.o':
            text += obj + ': ../native/utf8-width.inc\n'
    text += '\nsizes:\n'
    if len(objects) == 1:
        # Native size omits the filename for a single input.
        text += '\t@echo ' + objects[0] + ':\n'
    text += '\tsize ${OBJS}\n'
    return text


def native_makefile(groups, all_objects, profile, flags):
    program = 'tmux' if profile == 'milestone' else 'tmux-full'
    text = GENERATED + ' Run from upstream.\n'
    text += '# Clean shared objects before changing profile.\n'
    text += 'PROFILE=' + profile + '\nPROG=' + program + '\n'
    text += 'LINK_SCRIPT=../native/link-' + profile + '.sh\n'
    text += 'CC=' + CC + '\nCFLAGS=' + flags + '\n'
    text += 'GROUPS=' + ' '.join(name for name, _ in groups) + '\n\n'
    text += 'all: ${PROG}\n\n'
    text += '../tools/cc211:\n\tcd ../tools && make cc211\n\n'
    text += '../tools/ld211: ../tools/cc211\n\tcd ../tools && make ld211\n\n'
    # Explicit shell and aggregate status are required by the native make.
    # Do not add -k: this old make can return success after failed recipes.
    text += ('objects: ../tools/cc211\n'
             '\t@/bin/sh -c \'status=0; for group in ${GROUPS}; do '
             'make -f ../native-mk/$$group.mk CC="${CC}" CFLAGS="${CFLAGS}" '
             'all sizes || status=1; done; exit $$status\'\n\n')
    text += ('sizes:\n'
             '\t@/bin/sh -c \'status=0; for group in ${GROUPS}; do '
             'make -f ../native-mk/$$group.mk sizes || status=1; '
             'done; exit $$status\'\n\n')
    for name, _ in groups:
        text += name + ': ../tools/cc211\n'
        text += ('\tmake -f ../native-mk/' + name + '.mk CC="${CC}" '
                 'CFLAGS="${CFLAGS}" all sizes\n\n')
    text += ('${PROG}: FORCE ../tools/ld211\n'
             '\tmake -f ../Makefile.211bsd objects\n'
             '\t/bin/sh ${LINK_SCRIPT}\n'
             '\tsize ${PROG}\n\n')
    # Remove both profiles' known objects in bounded commands. In particular,
    # do not pass a full wildcard expansion to an old exec with limited argv.
    text += 'clean-objects:\n'
    for _, objects in chunks(all_objects):
        text += '\trm -f ' + ' '.join(objects) + '\n'
    text += '\nclean: clean-objects\n\trm -f ${PROG}\n\nFORCE:\n'
    return text


def root_makefile():
    text = GENERATED + '\n'
    for target in ['all', 'objects', 'sizes', 'G01', 'clean-objects', 'clean']:
        text += '\n' + target + ':\n'
        text += '\tcd upstream && make -f ../Makefile.211bsd ' + target + '\n'
    return text


def generate(root, profile):
    all_objects = read_full_objects(root)
    objects = select_objects(root, all_objects, profile)
    groups = chunks(objects)
    flags = BASE_CFLAGS + (' -DTMUX_MILESTONE' if profile == 'milestone' else '')
    outputs = {root / 'Makefile': root_makefile(),
               root / 'Makefile.211bsd': native_makefile(groups, all_objects, profile, flags),
               root / 'native/objects.list': '\n'.join(objects) + '\n'}
    directory = root / 'native-mk'
    directory.mkdir(exist_ok=True)
    for name, members in groups:
        outputs[directory / (name + '.mk')] = child_makefile(root, name, members, flags)
    for path, text in outputs.items():
        path.write_text(text)
    for old in directory.glob('G[0-9][0-9].mk'):
        if old not in outputs:
            if not old.read_text().startswith(GENERATED):
                raise ValueError('Refusing to remove non-generated makefile: ' + str(old))
            old.unlink()
    return len(objects), len(groups)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--profile', choices=('milestone', 'full'), default='milestone')
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args()
    count, groups = generate(args.root.resolve(), args.profile)
    print('Generated %s profile: %d objects in %d small makefiles' %
          (args.profile, count, groups))


if __name__ == '__main__':
    main()
