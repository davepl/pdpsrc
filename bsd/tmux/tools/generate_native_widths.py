#!/usr/bin/env python3
"""Generate a data-free balanced Unicode-width lookup from utf8.c's table.

The original host table is authoritative. Native code uses only comparisons,
returns and 32-bit immediate constants; unlisted codepoints retain width one.
Small helper functions also bound the native optimizer's per-function work.
Run after changing the table: python3 tools/generate_native_widths.py
"""
from pathlib import Path
import argparse
import re

TABLE = re.compile(r'struct utf8_width_entry utf8_width_table\[\]\s*=\s*\{(.*?)^\};', re.M | re.S)
MAX_HELPER_INTERVALS = 16
ROW = re.compile(r'\s*\{\s*(0x[0-9a-fA-F]+)[lL]?\s*,\s*(0x[0-9a-fA-F]+)[lL]?\s*,\s*([012])\s*,\s*NULL\s*,\s*NULL\s*\},?\s*')


def ranges(text):
    match = TABLE.search(text)
    if not match:
        raise ValueError('Cannot find canonical UTF-8 width table')
    entries = []
    for line in match[1].splitlines():
        if not line.strip():
            continue
        row = ROW.fullmatch(line)
        if not row:
            raise ValueError('Unrecognized width table row: ' + line)
        low, high, width = int(row[1], 16), int(row[2], 16), int(row[3])
        if not 0 <= low <= high <= 0x10ffff:
            raise ValueError('Invalid Unicode interval: ' + line)
        entries.append((low, high, width))
    entries.sort()
    for previous, current in zip(entries, entries[1:]):
        if previous[1] >= current[0]:
            raise ValueError(f'Overlapping width intervals: {previous}, {current}')
    return entries


def decision_tree(entries, indent=''):
    if not entries:
        return indent + 'return (1);\n'
    middle = len(entries) // 2
    low, high, width = entries[middle]
    return (indent + f'if (value < 0x{low:x}L) {{\n' +
            decision_tree(entries[:middle], indent + '\t') +
            indent + f'}} else if (value <= 0x{high:x}L) {{\n' +
            indent + f'\treturn ({width});\n' +
            indent + '} else {\n' +
            decision_tree(entries[middle + 1:], indent + '\t') +
            indent + '}\n')


def routing_tree(groups, first=0, indent=''):
    """Route a codepoint to one of the contiguous, nonoverlapping partitions."""
    if len(groups) == 1:
        return indent + f'return (utf8_width_part_{first}(value));\n'
    middle = len(groups) // 2
    boundary = groups[middle][0][0]
    return (indent + f'if (value < 0x{boundary:x}L) {{\n' +
            routing_tree(groups[:middle], first, indent + '\t') +
            indent + '} else {\n' +
            routing_tree(groups[middle:], first + middle, indent + '\t') +
            indent + '}\n')


def width_functions(entries):
    """Emit children first, then a small router, without static data."""
    if not entries:
        raise ValueError('The width table must not be empty')
    groups = [entries[start:start + MAX_HELPER_INTERVALS]
              for start in range(0, len(entries), MAX_HELPER_INTERVALS)]
    result = ''
    for index, group in enumerate(groups):
        assert 1 <= len(group) <= MAX_HELPER_INTERVALS
        result += (f'/* {len(group)} intervals; bounded optimizer work. */\n'
                   'static u_int\n' +
                   f'utf8_width_part_{index}(uint32_t value)\n' +
                   '{\n' + decision_tree(group, '\t') + '}\n\n')
    return (result + 'static u_int\nutf8_width_lookup(uint32_t value)\n' +
            '{\n' + routing_tree(groups, indent='\t') + '}\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = args.root.resolve()
    source = (root / 'upstream/utf8.c').read_text()
    entries = ranges(source)
    # Retain the source's copyright/license with this derived implementation.
    license_text = source[:source.index('#include')]
    result = ('/* Generated by tools/generate_native_widths.py; edit upstream/utf8.c.\n'
              f' * {len(entries)} nonoverlapping intervals; gaps return width 1.\n'
              f' * At most {MAX_HELPER_INTERVALS} intervals per helper to bound native optimizer work.\n'
              ' * Code only: no arrays, static data or allocated tree nodes.\n */\n' +
              license_text + width_functions(entries))
    target = root / 'native/utf8-width.inc'
    if args.check:
        if not target.exists() or target.read_text() != result:
            raise SystemExit('native/utf8-width.inc is stale')
    elif not target.exists() or target.read_text() != result:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(result)
    print(f'Generated balanced width code for {len(entries)} intervals '
          f'in {(len(entries) + MAX_HELPER_INTERVALS - 1) // MAX_HELPER_INTERVALS} helpers '
          f'of at most {MAX_HELPER_INTERVALS} intervals')


if __name__ == '__main__':
    main()
