#!/usr/bin/env python3
"""Keep stable translation IDs but strip prose unreachable in the compact profile.
Conservative whole-unit reference scan includes bfu/types archive members, so
linker selection cannot accidentally remove a live dialog label. No C parser
or target preprocessor is required; disabled branches are retained safely.
"""
from pathlib import Path
import re
p=Path(__file__).resolve().parents[1]/'upstream'
units='af_unix beos cache charsets connect cookies default dns error file html html_r html_tbl http https kbd kbdbind language main menu_compact os_dep sched select session terminal url view win32 bfu types'.split()
used=set()
for unit in units:
 text=(p/(unit+'.c')).read_text(encoding='latin1')
 text=re.sub(r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"',' ',text,flags=re.S)
 used.update(re.findall(r'\bT_\w+\b',text))
text=(p/'language-small.inc').read_text(encoding='latin1')
rows=re.findall(r'^\s*\{\s*(T_\w+|0),\s*(.*?)\s*\},?\s*$',text,re.M)
assert rows[0]==("0", "NULL") and rows[-1]==("0", "NULL")
registry=dict(re.findall(r"^#define\s+(T_\w+)\s+(\d+)\s*$",(p/"language.h").read_text(encoding="latin1"),re.M))
assert len(rows)>300
for index,(key,value) in enumerate(rows[1:-1],1):
 assert int(registry[key])==index,(key,index,registry[key])
out=['/* Generated by tools/generate_compact_language.py; IDs remain positional. */\nstruct translation translation_english[] = {\n']
saved=0; omitted=[]
for key,value in rows:
 if key!='0' and key not in used:
  saved+=sum(len(bytes(s,'latin1').decode('unicode_escape'))+1 for s in re.findall(r'"((?:\\.|[^"\\])*)"',value))
  omitted.append(key);value='""'
 out.append('  { '+value+' }, /* '+key+' */\n')
out.append('};\nstruct translation_desc translations[] = { {translation_english}, {NULL} };\n')
(p/'language-compact.inc').write_text(''.join(out),encoding='latin1')
print('Omitted',len(omitted),'unused translations; raw string bytes saved',saved,'plus',len(rows)*2,'target ID bytes')
