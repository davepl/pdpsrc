#!/usr/bin/env python3
"""Generate target-independent English sidecar: magic/count/size, BE16 offsets, NUL strings."""
from pathlib import Path
import re,struct
root=Path(__file__).resolve().parents[1];p=root/'upstream'
rows=re.findall(r'^\s*\{\s*(T_\w+|0),\s*(.*?)\s*\},?\s*$',(p/'language-small.inc').read_text(encoding='latin1'),re.M)
registry=dict(re.findall(r'^#define\s+(T_\w+)\s+(\d+)\s*$',(p/'language.h').read_text(encoding='latin1'),re.M))
assert rows[0]==('0','NULL') and rows[-1]==('0','NULL')
for i,(key,_) in enumerate(rows[1:-1],1):assert int(registry[key])==i
version=re.search(r'^#define VERSION "([^"]+)"',(root/'config.211bsd.h').read_text(),re.M)[1]
copy=re.search(r'^#define LINKS_COPYRIGHT ("[^"\n]*")',(p/'links-full.h').read_text(encoding='latin1'),re.M)[1]
strings=[]
for key,value in rows:
 value=value.replace('VERSION_STRING','"'+version+'"').replace('LINKS_COPYRIGHT',copy)
 if value=='NULL':b=b''
 else:
  tokens=re.findall(r'"((?:\\.|[^"\\])*)"',value)
  assert not re.sub(r'"(?:\\.|[^"\\])*"','',value).strip(),value
  b=''.join(bytes(t.replace(r'\?', '?'),'latin1').decode('unicode_escape') for t in tokens).encode('latin1')
 assert len(b)<1024 and b'\0' not in b
 strings.append(b+b'\0')
n=len(strings);offset=12+2*(n+1);offsets=[]
for b in strings:offsets.append(offset);offset+=len(b)
offsets.append(offset);assert offset<65536
(p/'language.dat').write_bytes(b'LNKENG1\n'+struct.pack('>HH',n,offset)+struct.pack('>'+'H'*(n+1),*offsets)+b''.join(strings))
(p/'language-data.h').write_text('/* Generated by generate_language_data.py */\n#define LANGUAGE_DATA_COUNT '+str(n)+'\n')
print('Generated language.dat:',n,'stable IDs,',offset,'bytes')
