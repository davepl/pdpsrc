#!/usr/bin/env python3
"""Generate native compilation copies with literal translation IDs.
Usage: generate_native_sources.py [upstream-directory]
Writes <unit>.native.c beside original sources to preserve quoted include paths.
Requires language.h's native macro definitions guarded by
#ifndef PDP11_LITERAL_IDS. Compile copies with -DPDP11_UNIT_<original unit>.
Canonical sources and language.h are never modified by this tool.
"""
import pathlib,re,sys
from compact_diagnostics import compact_diagnostics
p=pathlib.Path(sys.argv[1] if len(sys.argv)>1 else pathlib.Path(__file__).resolve().parent.parent/'upstream')
h=(p/'language.h').read_text(encoding='latin1')
m=list(re.finditer(r'^#else\n(?=#define T__CHAR_SET\b)',h,re.M))
if not m: raise SystemExit('Missing complete non-native language ID registry')
rows=re.findall(r'^#define\s+(T_\w+)\s+(\d+)\s*$',h[m[-1].end():],re.M)
ids=dict(rows)
if len(ids)<300: raise SystemExit('Incomplete language ID registry')
# Order matters: protect all quoted/comment content before matching identifiers.
pattern=re.compile(r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|\bT_\w+\b',re.S)
def literalize(text):
 def replace(match):
  token=match.group(0)
  if re.fullmatch(r'T_\w+',token):
   if token not in ids: raise ValueError('Unknown translation identifier '+token)
   return ids[token]
  return token
 return pattern.sub(replace,text)
count=0
diag_count=diag_bytes=0
for src in sorted(p.glob('*.c')):
 if src.name.endswith('.native.c'): continue
 text=src.read_text(encoding='latin1')
 try:
  body=literalize(text)
  body,n,b=compact_diagnostics(body)
  diag_count+=n;diag_bytes+=b
 except ValueError as exc: raise SystemExit(str(src)+': '+str(exc))
 output='/* Generated by tools/generate_native_sources.py; edit '+src.name+' instead. */\n#define PDP11_LITERAL_IDS 1\n#define PDP11_SOURCE_FILE \"'+src.name+'\"\n'+body
 (p/(src.stem+'.native.c')).write_text(output,encoding='latin1')
 count+=1
print('Generated',count,'native source copies with',len(ids),'known translation IDs')

print("Compacted",diag_count,"internal diagnostics;",diag_bytes,"raw literal bytes removed (all source units)")
